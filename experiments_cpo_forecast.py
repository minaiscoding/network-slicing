class TrainerCPOForecast:
    """Train CPO agent with forecast and cycling curriculum learning."""

    def __init__(self):
        os.makedirs('./results/500k/CPO_forecast/', exist_ok=True)

    def train(self, run_id: int):
        global _CURRENT_RUN_ID, _ENV_INSTANCE_COUNT
        _CURRENT_RUN_ID = run_id
        _ENV_INSTANCE_COUNT[run_id] = 0

        print(f'\n{"="*60}')
        print(f'=== CPO FORECAST Training Run {run_id} ===')
        print(f'{"="*60}')
        print(f'Scenarios cycle: {" → ".join(SCENARIOS)} → ... (repeating)')
        print(f'Steps per scenario block: {STEPS_PER_SCENARIO}')
        print(f'Total steps: {_TOTAL_STEPS}')
        print(f'Forecast horizon: {_FORECAST_HORIZON}')
        print(f'Output: results/500k/CPO_forecast/history_{run_id}.npz')

        custom_cfgs = {
            "train_cfgs": {
                "total_steps": _TOTAL_STEPS,
                "device": "cuda:0",
            },
            "algo_cfgs": {
                "steps_per_epoch": 1000,
                "update_iters": 10,
                "batch_size": 128,
                "target_kl": 0.02,
                "entropy_coef": 0.01,
                "cost_limit": 25.0,
                "gamma": 0.99,
                "cost_gamma": 0.99,
                "lam": 0.95,
                "lam_c": 0.95,
                "cg_damping": 0.1,
                "cg_iters": 15,
                "use_cost": True,
            },
            "model_cfgs": {
                "actor": {"hidden_sizes": [128, 128], "activation": "tanh"},
                "critic": {"hidden_sizes": [128, 128], "activation": "tanh", "lr": 0.001},
            },
            "logger_cfgs": {
                "use_wandb": False,
                "save_model_freq": 1,
            },
        }

        agent = omnisafe.Agent(
            algo="CPO",
            env_id=ENV_ID,
            custom_cfgs=custom_cfgs,
        )

        print('\nTraining started...')
        agent.learn()
        print('Training done!')

        try:
            agent.plot(smooth=1)
        except Exception as e:
            print(f'Plotting failed: {e}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(
        description="Train CPO with perfect forecast on RAN slicing"
    )
    parser.add_argument("--runs", type=int, default=RUNS)
    parser.add_argument("--processes", type=int, default=PROCESSES)
    parser.add_argument("--sequential", action="store_true")
    parser.add_argument("--steps-per-scenario", type=int, default=STEPS_PER_SCENARIO)
    parser.add_argument("--total-steps", type=int, default=TOTAL_STEPS)
    parser.add_argument("--forecast-horizon", type=int, default=FORECAST_HORIZON)
    args = parser.parse_args()

    STEPS_PER_SCENARIO = args.steps_per_scenario
    _TOTAL_STEPS = args.total_steps
    _FORECAST_HORIZON = args.forecast_horizon

    trainer = TrainerCPOForecast()
    run_list = list(range(args.runs))

    if args.sequential:
        for run in run_list:
            trainer.train(run)
    else:
        with cf.ProcessPoolExecutor(args.processes) as E:
            results = list(E.map(trainer.train, run_list))
